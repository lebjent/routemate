CREATE TABLE TB_TRAVEL_PRODUCT (
    PRODUCT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DEST_ID NUMBER(19) NOT NULL,
    PRODUCT_NAME VARCHAR2(150 CHAR) NOT NULL,
    PRODUCT_TYPE VARCHAR2(30 CHAR) NOT NULL,
    PROVIDER_NAME VARCHAR2(100 CHAR),
    PRODUCT_DESC CLOB,
    IMAGE_URL VARCHAR2(500 CHAR),
    BOOKING_URL VARCHAR2(1000 CHAR),
    PRICE NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) DEFAULT 'KRW' NOT NULL,
    USE_YN VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    SORT_ORDER NUMBER(10) DEFAULT 1 NOT NULL,
    CREATE_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRAVEL_PRODUCT PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT FK_PRODUCT_DEST FOREIGN KEY (DEST_ID) REFERENCES TB_DESTINATION (DEST_ID),
    CONSTRAINT CK_PRODUCT_USE CHECK (USE_YN IN ('Y', 'N')),
    CONSTRAINT CK_PRODUCT_PRICE CHECK (PRICE >= 0)
);

CREATE INDEX IX_PRODUCT_DEST_USE_SORT ON TB_TRAVEL_PRODUCT (DEST_ID, USE_YN, SORT_ORDER);
