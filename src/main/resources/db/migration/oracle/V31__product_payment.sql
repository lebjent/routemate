CREATE TABLE TB_PRODUCT_PAYMENT (
    PAYMENT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORDER_ID NUMBER(19) NOT NULL,
    PAYMENT_KEY VARCHAR2(100 CHAR) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'READY' NOT NULL,
    METHOD VARCHAR2(20 CHAR) DEFAULT 'MOCK' NOT NULL,
    CREATE_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PRODUCT_PAYMENT PRIMARY KEY (PAYMENT_ID),
    CONSTRAINT UK_PRODUCT_PAYMENT_ORDER UNIQUE (ORDER_ID),
    CONSTRAINT UK_PRODUCT_PAYMENT_KEY UNIQUE (PAYMENT_KEY),
    CONSTRAINT FK_PRODUCT_PAYMENT_ORDER FOREIGN KEY (ORDER_ID) REFERENCES TB_PRODUCT_ORDER (ORDER_ID)
);
