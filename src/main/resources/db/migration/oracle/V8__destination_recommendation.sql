CREATE TABLE TB_DEST_RECOMMEND (
    RECOMMEND_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DEST_ID NUMBER(19) NOT NULL,
    DISPLAY_START_DT TIMESTAMP(6) NOT NULL,
    DISPLAY_END_DT TIMESTAMP(6) NOT NULL,
    SORT_ORDER NUMBER(5) DEFAULT 1 NOT NULL,
    USE_YN VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_DEST_RECOMMEND PRIMARY KEY (RECOMMEND_ID),
    CONSTRAINT FK_DEST_RECOMMEND_DEST FOREIGN KEY (DEST_ID) REFERENCES TB_DESTINATION(DEST_ID)
);

CREATE INDEX IX_DEST_RECOMMEND_PERIOD ON TB_DEST_RECOMMEND (USE_YN, DISPLAY_START_DT, DISPLAY_END_DT, SORT_ORDER);
