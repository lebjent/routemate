CREATE TABLE TB_PRODUCT_ORDER (
    ORDER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ORDER_NO VARCHAR2(40 CHAR) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    PRODUCT_ID NUMBER(19),
    OPTION_ID NUMBER(19),
    PRODUCT_NAME VARCHAR2(150 CHAR) NOT NULL,
    OPTION_NAME VARCHAR2(150 CHAR) NOT NULL,
    PRODUCT_IMAGE_URL VARCHAR2(500 CHAR),
    DESTINATION_NAME VARCHAR2(150 CHAR) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    UNIT_PRICE NUMBER(12, 2) NOT NULL,
    TOTAL_PRICE NUMBER(12, 2) NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) NOT NULL,
    USE_DATE DATE NOT NULL,
    BUYER_NAME VARCHAR2(50 CHAR) NOT NULL,
    BUYER_EMAIL VARCHAR2(100 CHAR) NOT NULL,
    BUYER_PHONE VARCHAR2(20 CHAR),
    ORDER_STATUS VARCHAR2(20 CHAR) DEFAULT 'ORDERED' NOT NULL,
    PAYMENT_STATUS VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    CREATE_DT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PRODUCT_ORDER PRIMARY KEY (ORDER_ID),
    CONSTRAINT UK_PRODUCT_ORDER_NO UNIQUE (ORDER_NO),
    CONSTRAINT FK_ORDER_USER FOREIGN KEY (USER_ID) REFERENCES TB_USER_MSTR (USER_ID),
    CONSTRAINT FK_ORDER_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES TB_TRAVEL_PRODUCT (PRODUCT_ID) ON DELETE SET NULL,
    CONSTRAINT FK_ORDER_OPTION FOREIGN KEY (OPTION_ID) REFERENCES TB_TRAVEL_PRODUCT_OPTION (OPTION_ID) ON DELETE SET NULL,
    CONSTRAINT CK_ORDER_QUANTITY CHECK (QUANTITY BETWEEN 1 AND 10),
    CONSTRAINT CK_ORDER_UNIT_PRICE CHECK (UNIT_PRICE >= 0),
    CONSTRAINT CK_ORDER_TOTAL_PRICE CHECK (TOTAL_PRICE >= 0)
);

CREATE INDEX IX_PRODUCT_ORDER_USER_DT ON TB_PRODUCT_ORDER (USER_ID, CREATE_DT);

