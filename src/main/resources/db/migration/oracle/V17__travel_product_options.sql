CREATE TABLE TB_TRAVEL_PRODUCT_OPTION (
    OPTION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PRODUCT_ID NUMBER(19) NOT NULL,
    OPTION_NAME VARCHAR2(150 CHAR) NOT NULL,
    OPTION_DESC VARCHAR2(500 CHAR),
    PRICE NUMBER(12, 2) DEFAULT 0 NOT NULL,
    CURRENCY VARCHAR2(3 CHAR) DEFAULT 'KRW' NOT NULL,
    CANCELLATION_POLICY VARCHAR2(500 CHAR),
    VALIDITY_TEXT VARCHAR2(200 CHAR),
    CONFIRMATION_TYPE VARCHAR2(20 CHAR) DEFAULT 'INSTANT' NOT NULL,
    USE_YN VARCHAR2(1 CHAR) DEFAULT 'Y' NOT NULL,
    SORT_ORDER NUMBER(10) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_TRAVEL_PRODUCT_OPTION PRIMARY KEY (OPTION_ID),
    CONSTRAINT FK_PRODUCT_OPTION_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES TB_TRAVEL_PRODUCT (PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT CK_PRODUCT_OPTION_USE CHECK (USE_YN IN ('Y', 'N')),
    CONSTRAINT CK_PRODUCT_OPTION_PRICE CHECK (PRICE >= 0)
);

CREATE INDEX IX_PRODUCT_OPTION_PRODUCT_SORT ON TB_TRAVEL_PRODUCT_OPTION (PRODUCT_ID, SORT_ORDER);
