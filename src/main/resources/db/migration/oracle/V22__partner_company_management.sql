CREATE TABLE TB_PARTNER_COMPANY (
    PARTNER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PARTNER_CODE VARCHAR2(30 CHAR) NOT NULL,
    PARTNER_NAME VARCHAR2(120 CHAR) NOT NULL,
    BUSINESS_NUMBER VARCHAR2(30 CHAR),
    REPRESENTATIVE_NAME VARCHAR2(50 CHAR),
    MANAGER_NAME VARCHAR2(50 CHAR),
    MANAGER_EMAIL VARCHAR2(100 CHAR),
    MANAGER_PHONE VARCHAR2(30 CHAR),
    WEBSITE_URL VARCHAR2(500 CHAR),
    COMMISSION_RATE NUMBER(5, 2) DEFAULT 0 NOT NULL,
    CONTRACT_START_DATE DATE,
    CONTRACT_END_DATE DATE,
    PARTNER_STATUS VARCHAR2(20 CHAR) DEFAULT 'ONBOARDING' NOT NULL,
    MEMO VARCHAR2(1000 CHAR),
    CREATE_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    MDFY_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PARTNER_COMPANY PRIMARY KEY (PARTNER_ID),
    CONSTRAINT UK_PARTNER_CODE UNIQUE (PARTNER_CODE),
    CONSTRAINT UK_PARTNER_BUSINESS_NO UNIQUE (BUSINESS_NUMBER),
    CONSTRAINT CK_PARTNER_COMMISSION CHECK (COMMISSION_RATE BETWEEN 0 AND 100),
    CONSTRAINT CK_PARTNER_STATUS CHECK (PARTNER_STATUS IN ('ONBOARDING', 'ACTIVE', 'SUSPENDED', 'TERMINATED'))
);

ALTER TABLE TB_TRAVEL_PRODUCT ADD (
    PARTNER_ID NUMBER(19),
    REGISTRATION_SOURCE VARCHAR2(20 CHAR) DEFAULT 'ADMIN' NOT NULL,
    APPROVAL_STATUS VARCHAR2(20 CHAR) DEFAULT 'APPROVED' NOT NULL,
    APPROVAL_MEMO VARCHAR2(500 CHAR),
    SUBMIT_DT TIMESTAMP(6),
    APPROVE_DT TIMESTAMP(6),
    CONSTRAINT FK_PRODUCT_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES TB_PARTNER_COMPANY (PARTNER_ID),
    CONSTRAINT CK_PRODUCT_SOURCE CHECK (REGISTRATION_SOURCE IN ('ADMIN', 'PARTNER')),
    CONSTRAINT CK_PRODUCT_APPROVAL CHECK (APPROVAL_STATUS IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED'))
);

INSERT INTO TB_PARTNER_COMPANY (
    PARTNER_CODE, PARTNER_NAME, PARTNER_STATUS, COMMISSION_RATE, MEMO
)
SELECT 'LEGACY-' || LPAD(source.RN, 3, '0'),
       source.PROVIDER_NAME,
       'ACTIVE',
       12,
       '기존 상품 판매처에서 자동 전환된 파트너사'
FROM (
    SELECT PROVIDER_NAME, ROW_NUMBER() OVER (ORDER BY PROVIDER_NAME) AS RN
    FROM (SELECT DISTINCT PROVIDER_NAME FROM TB_TRAVEL_PRODUCT WHERE PROVIDER_NAME IS NOT NULL)
) source
WHERE NOT EXISTS (
    SELECT 1 FROM TB_PARTNER_COMPANY partner WHERE partner.PARTNER_NAME = source.PROVIDER_NAME
);

MERGE INTO TB_TRAVEL_PRODUCT product
USING (
    SELECT p.PRODUCT_ID, partner.PARTNER_ID
    FROM TB_TRAVEL_PRODUCT p
    JOIN TB_PARTNER_COMPANY partner ON partner.PARTNER_NAME = p.PROVIDER_NAME
    WHERE p.PARTNER_ID IS NULL
) source
ON (source.PRODUCT_ID = product.PRODUCT_ID)
WHEN MATCHED THEN UPDATE SET
    product.PARTNER_ID = source.PARTNER_ID,
    product.APPROVAL_STATUS = 'APPROVED',
    product.APPROVE_DT = product.CREATE_DT;

