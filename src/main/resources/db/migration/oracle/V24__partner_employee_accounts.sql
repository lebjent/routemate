CREATE TABLE TB_PARTNER_USER (
    PARTNER_USER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PARTNER_ID NUMBER(19) NOT NULL,
    USER_ID NUMBER(19) NOT NULL,
    PARTNER_ROLE VARCHAR2(20 CHAR) NOT NULL,
    USE_YN CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    CREATE_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    MDFY_DT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PARTNER_USER PRIMARY KEY (PARTNER_USER_ID),
    CONSTRAINT UK_PARTNER_USER_USER UNIQUE (USER_ID),
    CONSTRAINT UK_PARTNER_USER_MAPPING UNIQUE (PARTNER_ID, USER_ID),
    CONSTRAINT FK_PARTNER_USER_PARTNER FOREIGN KEY (PARTNER_ID) REFERENCES TB_PARTNER_COMPANY (PARTNER_ID),
    CONSTRAINT FK_PARTNER_USER_USER FOREIGN KEY (USER_ID) REFERENCES TB_USER_MSTR (USER_ID),
    CONSTRAINT CK_PARTNER_USER_ROLE CHECK (PARTNER_ROLE IN ('OWNER', 'STAFF')),
    CONSTRAINT CK_PARTNER_USER_USE CHECK (USE_YN IN ('Y', 'N'))
);

CREATE INDEX IX_PARTNER_USER_PARTNER_ROLE ON TB_PARTNER_USER (PARTNER_ID, PARTNER_ROLE, USE_YN);
